// Generates src/ui/icons.gen.ts from the storyboard's Phosphor 2.1.1 SVGs (one path each, 256 x 256 view box).
// Usage: node scripts/icons.mjs <dir with regular/ and fill/>   (default: the handoff bundle's icons/svg)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(process.argv[2] ?? "../../.agents/handoff/mobile-final/icons/svg");
const icons = {};
for (const weight of ["regular", "fill"]) {
	for (const file of readdirSync(join(root, weight)).sort()) {
		if (!file.endsWith(".svg")) continue;
		const paths = [...readFileSync(join(root, weight, file), "utf8").matchAll(/<path[^>]*\sd="([^"]+)"/g)].map(
			(m) => m[1],
		);
		if (paths.length === 0) throw new Error(`${weight}/${file}: no <path>`);
		(icons[file.slice(0, -4).replace(/-fill$/, "")] ??= {})[weight] = paths.join(" ");
	}
}
const body = Object.entries(icons)
	.map(([name, w]) => `\t${JSON.stringify(name)}: ${JSON.stringify(w)},`)
	.join("\n");
writeFileSync(
	resolve("src/ui/icons.gen.ts"),
	`// Generated by scripts/icons.mjs from Phosphor 2.1.1 (MIT). Do not edit.\nexport const icons = {\n${body}\n} as const satisfies Record<string, { regular?: string; fill?: string }>;\nexport type IconName = keyof typeof icons;\n`,
);
console.log(`${Object.keys(icons).length} icons`);
