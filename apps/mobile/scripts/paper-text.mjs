// Generates src/dev/storyboard/paper-text.gen.ts: the text that the storyboard's page fixtures contain, as boxes
// relative to the page (0..1). The app shows those pages as images (the PageRenderer's output), so in storyboard
// captures the Page component reports the fixture's text at the place its image puts it; the layout comparison then
// checks the page's position and scale through them. Source: design/layout/<ID>.json (elements inside "Page").
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const bundle = resolve(process.argv[2] ?? "../../.agents/handoff/mobile-final");
const ids = ["B1-Overview", "B6-Design", "B18-Preview", "P1-Public"];
const out = {};
for (const id of ids) {
	const { elements } = JSON.parse(readFileSync(resolve(bundle, "design/layout", `${id}.json`), "utf8"));
	const at = elements.findIndex((e) => e.component === "Page");
	if (at < 0) throw new Error(`${id}: no Page`);
	const page = elements[at];
	const r = (v) => Math.round(v * 1e5) / 1e5;
	out[id] = [];
	for (const e of elements.slice(at + 1)) {
		if (e.depth <= page.depth) break;
		if (!e.text || e.offscreen) continue;
		const b = e.textBox ?? e.box;
		out[id].push({
			text: e.text,
			x: r((b.x - page.box.x) / page.box.w),
			y: r((b.y - page.box.y) / page.box.h),
			w: r(b.w / page.box.w),
			h: r(b.h / page.box.h),
		});
	}
}
writeFileSync(
	resolve("src/dev/storyboard/paper-text.gen.ts"),
	`// Generated by scripts/paper-text.mjs from the storyboard layout dumps. Do not edit.\nexport type PaperText = { text: string; x: number; y: number; w: number; h: number };\nexport const paperText: Record<string, PaperText[]> = ${JSON.stringify(out, null, "\t")};\n`,
);
console.log(
	Object.entries(out)
		.map(([k, v]) => `${k}: ${v.length}`)
		.join(", "),
);
